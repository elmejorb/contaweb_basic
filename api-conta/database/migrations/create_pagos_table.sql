CREATE TABLE IF NOT EXISTS `pagos` (
    `id_pago` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `id_empresa` BIGINT UNSIGNED NOT NULL,
    `id_pago_vb6` INT NULL COMMENT 'Id_Pagos original de VB6',
    `rec_caja_n` INT NULL COMMENT 'Número de recibo de caja',
    `codigo_cliente` VARCHAR(50) NULL COMMENT 'Código del cliente',
    `factura_n` INT NULL COMMENT 'Número de factura',
    `valor_pago` DECIMAL(19,4) NOT NULL DEFAULT 0,
    `fecha` DATE NULL,
    `detalle_pago` VARCHAR(255) NULL,
    `valor_factura` DECIMAL(19,4) NOT NULL DEFAULT 0,
    `saldo_actual` DECIMAL(19,4) NOT NULL DEFAULT 0,
    `descuento` DECIMAL(19,4) NULL DEFAULT 0,
    `retencion` DECIMAL(19,4) NULL DEFAULT 0,
    `iva_retenido` DECIMAL(19,4) NULL DEFAULT 0,
    `estado` VARCHAR(10) NULL,
    `saldo_total` DECIMAL(19,4) NULL DEFAULT 0,
    `cedula` VARCHAR(20) NULL,
    `recibido_de` VARCHAR(60) NULL,
    `created_at` TIMESTAMP NULL,
    `updated_at` TIMESTAMP NULL,
    PRIMARY KEY (`id_pago`),
    INDEX `pagos_id_empresa_index` (`id_empresa`),
    INDEX `pagos_codigo_cliente_index` (`codigo_cliente`),
    INDEX `pagos_id_pago_vb6_index` (`id_pago_vb6`, `id_empresa`),
    CONSTRAINT `pagos_id_empresa_foreign` FOREIGN KEY (`id_empresa`) REFERENCES `empresas` (`id_empresa`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
